class Data:
    def __init__(self, brand_path: Path):
        self.root = brand_path.parent
        self.brand = json.loads(brand_path.read_text())
        mf = self.root / "assets" / "manifest.json"
        self.manifest = json.loads(mf.read_text()) if mf.exists() else {"files": [], "warnings": []}
        self.platforms = json.loads(PLATFORMS_FILE.read_text())
        self.sem = generate_tokens.semantic_aliases(self.brand)

    def files(self, prefix: str, suffix: tuple = (".png", ".svg")):
        return [f for f in self.manifest["files"] if f["path"].startswith(prefix) and f["path"].endswith(suffix)]


def _ratio_cell(ratio, required=None):
    ok = ratio >= (required or 4.5)
    return f"{ratio:.2f}:1 — {'Pass ✓' if ok else 'Fail ✗'}" if required is not None else f"{ratio:.2f}:1 ({bl.rating_label(ratio)})"


def chip(hex_value, label=None):
    return {"swatch": hex_value, "text": label or hex_value}


