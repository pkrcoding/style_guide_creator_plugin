def header_logo(d: Data) -> str:
    """<picture> that swaps to the reversed logo in dark mode, so the header logo keeps its contrast."""
    paths = [f["path"] for f in d.manifest["files"]]

    def find(*suffixes):
        return next((p for s in suffixes for p in paths if p.endswith(s)), None)

    light_bg = d.sem["light"]["surface-subtle"]
    variant = next((t["recommendedVariant"] for t in d.manifest.get("backgroundTests", []) if t["background"] == "light-neutral"), None)
    if variant is None:  # No raster tests: use full colour only if every logo colour is >= 3:1 on the header.
        cols = d.brand.get("color", {}).get("brand", [])
        variant = "full-colour" if all(bl.contrast_ratio(c["hex"], light_bg) >= 3 for c in cols) else "mono-dark"
    solid = d.brand["logo"].get("monoStyle") == "solid"
    knock = () if solid or not variant.startswith("mono") else (f"primary-{variant}-knockout.png",)
