"""Render the style guide from brand.json + content/*.md + assets/manifest.json.

Outputs at the guide root:
  style-guide.html   accessible, responsive, light/dark, print-ready single page
  style-guide.md     the same content as portable Markdown
  style-guide.pdf    only with --pdf and a headless Chrome/Chromium/Edge available

Chapter Markdown supports headings, paragraphs, lists, tables, blockquotes, code,
links, images, and callouts (a blockquote starting with **Do**, **Don't**, **Note**
or **Accessibility**). Lines containing only a placeholder such as {{color.pairings}}
are replaced with tables and galleries generated from the data.

Usage:
    render_guide.py path/to/brand.json [--pdf]
"""

