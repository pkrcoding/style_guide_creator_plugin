def inline(text: str) -> str:
    codes: list[str] = []

    def keep(m):
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+&quot;[^&]*&quot;)?\)",
                  lambda m: f'<img src="{html.escape(m.group(2), quote=True)}" alt="{html.escape(m.group(1), quote=True)}" loading="lazy">', text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{html.escape(m.group(2), quote=True)}">{m.group(1)}</a>', text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"(?<![\w_])_([^_\n]+)_(?![\w_])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


class Slugger:
    def __init__(self):
        self.seen: dict = {}

    def __call__(self, text):
        base = bl.slugify(re.sub(r"<[^>]+>", "", text)) or "section"
        n = self.seen.get(base, 0)
        self.seen[base] = n + 1
        return base if n == 0 else f"{base}-{n}"


def md_to_html(md: str, slug: Slugger, render_ph, shift: int = 1, toc: list | None = None) -> str:
    lines = md.splitlines()
    out: list[str] = []
    para: list[str] = []
    i = 0
    current = shift + 1  # Level of the most recent heading; generated sub-headings go one below it.
    last_heading = ""
    pending_caption = None

    def flush():
        if para:
            out.append(f"<p>{inline(' '.join(s.strip() for s in para))}</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if s.startswith("<!--"):
            flush()
            while "-->" not in lines[i]:
                i += 1
            i += 1
            continue
        if not s:
            flush()
            i += 1
            continue
        m = re.fullmatch(r"\{\{([\w.]+)\}\}", s)
        if m:
            flush()
            out.append(render_ph(m.group(1), current))
            i += 1
            continue
        if s.startswith("```"):
            flush()
            lang = s[3:].strip()
            code = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            out.append(f'<pre><code{f" class=language-{html.escape(lang)}" if lang else ""}>{html.escape(chr(10).join(code))}</code></pre>')
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", s)
        if m:
            flush()
            level = min(6, len(m.group(1)) + shift)
            current = level
            text = inline(m.group(2).strip())
            last_heading = re.sub(r"<[^>]+>", "", text)
            hid = slug(text)
            if toc is not None and level <= 3:
                toc.append((level, hid, re.sub(r"<[^>]+>", "", text)))
            out.append(f'<h{level} id="{hid}">{text}</h{level}>')
            i += 1
            continue
        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", s):
            flush()
            out.append("<hr>")
            i += 1
            continue
        m = re.fullmatch(r"Table:\s*(.+)", s)
        if m and i + 1 < len(lines) and (lines[i + 1].strip().startswith("|") or (i + 2 < len(lines) and not lines[i + 1].strip() and lines[i + 2].strip().startswith("|"))):
            flush()
            pending_caption = m.group(1).strip()
            i += 1
            continue
        if s.startswith("|") and i + 1 < len(lines) and re.fullmatch(r"\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?", lines[i + 1].strip()):
            flush()
            head = [c.strip() for c in s.strip("|").split("|")]
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            if pending_caption:
                out.append(html_table(pending_caption, head, rows, md_cells=True))
            else:  # Every table gets a caption; fall back to the section heading, shown to screen readers only.
                out.append(html_table(last_heading or head[0], head, rows, md_cells=True, hidden_caption=True))
            pending_caption = None
            continue
        if s.startswith(">"):
            flush()
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            inner = md_to_html("\n".join(quote), slug, render_ph, shift=shift)
            kind = re.match(r"\s*\*\*(Do|Don['’]t|Note|Accessibility|Warning)\b", quote[0] if quote else "")
            cls = {"do": "do", "don't": "dont", "don’t": "dont", "note": "note", "accessibility": "a11y", "warning": "warn"}.get(kind.group(1).lower(), "note") if kind else None
            out.append(f'<div class="callout callout-{cls}" role="note">{inner}</div>' if cls else f"<blockquote>{inner}</blockquote>")
            continue
        if re.match(r"^\s*([-*+]|\d+[.)])\s+", line):
            flush()
            block = []
            while i < len(lines) and (re.match(r"^\s*([-*+]|\d+[.)])\s+", lines[i]) or (lines[i].startswith("  ") and lines[i].strip())):
                block.append(lines[i])
                i += 1
            out.append(html_list(block))
            continue
        if s.startswith("<") and s.endswith(">"):
            flush()
            out.append(s)
            i += 1
            continue
        para.append(line)
        i += 1
    flush()
    return "\n".join(out)


def html_list(block: list[str]) -> str:
    """Render a list block; items indented by 2+ spaces nest inside the previous item."""
    parsed: list[list] = []
    for line in block:
        m = re.match(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$", line)
        if not m:
            parsed[-1][2] += " " + line.strip()
            continue
        parsed.append([len(m.group(1)) // 2, "ol" if m.group(2)[0].isdigit() else "ul", m.group(3)])
    out, stack = [], []
    for indent, tag, text in parsed:
        while stack and stack[-1][0] > indent:
            out.append(f"</li></{stack.pop()[1]}>")
        if stack and stack[-1][0] == indent and stack[-1][1] != tag:
            out.append(f"</li></{stack.pop()[1]}><{tag}>")
            stack.append((indent, tag))
        elif stack and stack[-1][0] == indent:
            out.append("</li>")
        else:
            out.append(f"<{tag}>")
            stack.append((indent, tag))
        out.append(f"<li>{inline(text)}")
    while stack:
        out.append(f"</li></{stack.pop()[1]}>")
    return "".join(out)


def cell_html(c, md_cells=False) -> str:
    if isinstance(c, dict):
        if "sample" in c:
            fg, bg = c["sample"]
            return f'<span class="sample" style="color:{fg};background:{bg}">{html.escape(c["text"])}</span>'
        return f'<span class="chip" style="background:{c["swatch"]}" aria-hidden="true"></span> <code>{html.escape(c["text"])}</code>'
    return inline(str(c))


def html_table(caption, head, rows, md_cells=False, hidden_caption=False) -> str:
    cls = ' class="visually-hidden"' if hidden_caption else ""
    cap = f"<caption{cls}>{inline(caption)}</caption>" if caption else ""
    th = "".join(f'<th scope="col">{inline(h)}</th>' for h in head)
    body = []
    for r in rows:
        cells = [f'<th scope="row">{cell_html(r[0])}</th>'] + [f"<td>{cell_html(c)}</td>" for c in r[1:]]
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f'<div class="table-wrap" data-label="{html.escape(caption or head[0], quote=True)}"><table>{cap}<thead><tr>{th}</tr></thead><tbody>{"".join(body)}</tbody></table></div>'


