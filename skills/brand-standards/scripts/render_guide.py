def ph_color_brand(d: Data):
    items = []
    for c in d.brand["color"]["brand"]:
        f = bl.colour_formats(c["hex"])
        on_white = bl.contrast_ratio(c["hex"], "#ffffff")
        dark_text = d.brand["color"]["neutral"]["scale"]["950"]
        white_on = bl.contrast_ratio("#ffffff", c["hex"])
        dark_on = bl.contrast_ratio(dark_text, c["hex"])
        best_label, best = ("White", white_on) if white_on >= dark_on else ("Dark", dark_on)
        text_step = c.get("accessible", {}).get("textOnLight")
        if on_white >= 4.5:
            text_line = "As text on white: use as is"
        elif text_step:
            text_line = f"As text on white: use {c['id']}-{text_step['step']} {text_step['hex']}"
        else:
            text_line = "As text on white: not suitable"
        items.append({
            "name": c["name"], "hex": c["hex"], "role": c.get("role", ""),
            "fg": "#ffffff" if white_on >= dark_on else dark_text,
            "lines": [f"HEX {f['hex']}", f["rgb"].upper().replace("RGB", "RGB "), f["hsl"].upper().replace("HSL", "HSL "), f["oklch"],
                      f"CMYK {f['cmyk']} (verify)", f"Pantone: {c.get('pantone') or 'to be matched'}",
                      f"On white: {_ratio_cell(on_white)}", f"{best_label} text on it: {_ratio_cell(best)}", text_line],
        })
    return [{"t": "swatches", "items": items}]


