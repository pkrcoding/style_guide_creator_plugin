def cell_md(c) -> str:
    if isinstance(c, dict):
        return c["text"] if "sample" in c else f"`{c['text']}`"
    return str(c).replace("|", "\\|").replace("\n", " ")


def blocks_md(blocks) -> str:
    out = []
    for b in blocks:
        t = b["t"]
        if t == "p":
            out.append(b["text"])
        elif t == "h":
            out.append(f"#### {b['text']}")
        elif t == "list":
            out.append("\n".join(f"- {x}" for x in b["items"]))
        elif t == "code":
            out.append(f"```html\n{b['text'].rstrip()}\n```")
        elif t == "table":
            lines = [f"**{b['caption']}**", ""] if b.get("caption") else []
            lines.append("| " + " | ".join(b["head"]) + " |")
            lines.append("|" + "---|" * len(b["head"]))
            lines += ["| " + " | ".join(cell_md(c) for c in r) + " |" for r in b["rows"]]
            out.append("\n".join(lines))
        elif t == "gallery":
            out.append("\n\n".join(f"![{it.get('alt', '')}]({it['src']})\n*{it.get('caption', '')}*" for it in b["items"]))
        elif t == "swatches":
            out.append("\n\n".join(f"**{it['name']}** ({it['role']})\n\n" + "\n".join(f"- {x}" for x in it["lines"] if x) for it in b["items"]))
        elif t == "bar":
            out.append(f"*{b['caption']}*\n\n" + "\n".join(f"- {it['label']}" for it in b["items"]))
        elif t == "specimen":
            out.append("\n".join(f"- {it['meta']}" for it in b["items"]))
        elif t == "spacing":
            continue  # The accompanying table covers it.
        elif t == "focus":
            out.append(f"Focus ring: {b['width']}px solid, {b['offset']}px offset; `{b['light']}` on light, `{b['dark']}` on dark surfaces.")
    return "\n\n".join(out)


